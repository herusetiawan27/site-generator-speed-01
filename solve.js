export const INCLUDE_DEPTH = 8;

const PATH = /^[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*$/;
const FOR = /^for ([A-Za-z_][A-Za-z0-9_]*) in (\S+)$/;
const IF = /^if (not )?(\S+)$/;
const INCLUDE = /^include "([a-z0-9-]+)"$/;

class TemplateError extends Error {}

function pathOf(name, text) {
  if (!PATH.test(text)) throw new TemplateError(`template "${name}": ${JSON.stringify(text)} is not a path`);
  return text.split('.');
}

function tokenize(name, src) {
  const tokens = [];
  let text = '';
  let i = 0;
  while (i < src.length) {
    const open = src.indexOf('{', i);
    if (open === -1 || open === src.length - 1) {
      text += src.slice(i);
      break;
    }
    const next = src[open + 1];
    if (next !== '{' && next !== '%') {
      text += src.slice(i, open + 1);
      i = open + 1;
      continue;
    }
    text += src.slice(i, open);
    if (next === '{') {
      const raw = src[open + 2] === '{';
      const close = src.indexOf(raw ? '}}}' : '}}', open + (raw ? 3 : 2));
      if (close === -1) throw new TemplateError(`template "${name}": a ${raw ? '{{{' : '{{'} is not closed`);
      if (text !== '') tokens.push({ t: 'text', text });
      text = '';
      tokens.push({ t: raw ? 'raw' : 'var', path: pathOf(name, src.slice(open + (raw ? 3 : 2), close).trim()) });
      i = close + (raw ? 3 : 2);
      continue;
    }
    const close = src.indexOf('%}', open + 2);
    if (close === -1) throw new TemplateError(`template "${name}": a {% is not closed`);
    const end = close + 2;
    const lineStart = src.lastIndexOf('\n', open - 1) + 1;
    const nl = src.indexOf('\n', end);
    const lineEnd = nl === -1 ? src.length : nl;
    const standalone = /^[ \t]*$/.test(src.slice(lineStart, open)) && /^[ \t]*$/.test(src.slice(end, lineEnd));
    if (standalone) text = text.slice(0, text.length - (open - lineStart));
    if (text !== '') tokens.push({ t: 'text', text });
    text = '';
    tokens.push({ t: 'tag', tag: src.slice(open + 2, close).trim() });
    i = standalone ? (nl === -1 ? src.length : nl + 1) : end;
  }
  if (text !== '') tokens.push({ t: 'text', text });
  return tokens;
}

function parseTemplate(name, src) {
  const root = { kind: 'root', body: [] };
  const stack = [root];
  let body = root.body;
  for (const tok of tokenize(name, src)) {
    if (tok.t === 'text') body.push({ kind: 'text', text: tok.text });
    else if (tok.t === 'var' || tok.t === 'raw') body.push({ kind: tok.t, path: tok.path });
    else {
      const tag = tok.tag;
      const top = stack[stack.length - 1];
      let m;
      if ((m = FOR.exec(tag)) !== null) {
        const node = { kind: 'for', name: m[1], path: pathOf(name, m[2]), body: [] };
        body.push(node);
        stack.push(node);
        body = node.body;
      } else if ((m = IF.exec(tag)) !== null) {
        const node = { kind: 'if', not: m[1] !== undefined, path: pathOf(name, m[2]), then: [], else: null };
        body.push(node);
        stack.push(node);
        body = node.then;
      } else if (tag === 'else') {
        if (top.kind !== 'if' || top.else !== null) throw new TemplateError(`template "${name}": an else outside an if`);
        top.else = [];
        body = top.else;
      } else if (tag === 'endfor' || tag === 'endif') {
        if (top.kind !== (tag === 'endfor' ? 'for' : 'if')) throw new TemplateError(`template "${name}": an ${tag} with no open ${tag.slice(3)}`);
        stack.pop();
        const parent = stack[stack.length - 1];
        body = parent.kind === 'root' ? parent.body : parent.kind === 'for' ? parent.body : parent.else ?? parent.then;
      } else if ((m = INCLUDE.exec(tag)) !== null) body.push({ kind: 'include', name: m[1] });
      else throw new TemplateError(`template "${name}": {% ${tag} %} is not a tag`);
    }
  }
  if (stack.length > 1) throw new TemplateError(`template "${name}": a ${stack[stack.length - 1].kind} is not closed`);
  return root.body;
}

/** The value at `path` in the scope chain (frames, innermost last): its first name from the nearest frame holding it, then own properties. */
function lookup(S, path) {
  for (let i = S.length - 1; i >= 0; i--) {
    const f = S[i];
    if (Object.hasOwn(f, path[0])) {
      let v = f[path[0]];
      for (let k = 1; k < path.length; k++) {
        if (v === null || typeof v !== 'object' || !Object.hasOwn(v, path[k])) return undefined;
        v = v[path[k]];
      }
      return v;
    }
  }
  return undefined;
}

function textOf(v) {
  if (typeof v === 'string') return v;
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return v.map(textOf).join(', ');
  return '';
}

function truthy(v) {
  if (Array.isArray(v)) return v.length > 0;
  return v !== undefined && v !== null && v !== false && v !== '' && v !== 0;
}

function renderNodes(nodes, S, ctx, depth) {
  let out = '';
  for (let ni = 0; ni < nodes.length; ni++) {
    const n = nodes[ni];
    switch (n.kind) {
      case 'text':
        out += n.text;
        break;
      case 'var':
        out += ctx.escape(textOf(resolveValue(S, n.res)));
        break;
      case 'raw':
        out += textOf(resolveValue(S, n.res));
        break;
      case 'if': {
        const v = truthy(resolveValue(S, n.res));
        const branch = v !== n.not ? n.then : n.else;
        if (branch !== null) out += renderNodes(branch, S, ctx, depth);
        break;
      }
      case 'for': {
        const xs = resolveValue(S, n.res);
        if (!Array.isArray(xs)) break;
        for (let k = 0; k < xs.length; k++) {
          const vars = {};
          vars[n.name] = xs[k];
          vars.loop = { index: k + 1, first: k === 0, last: k === xs.length - 1, length: xs.length };
          S.push(vars);
          out += renderNodes(n.body, S, ctx, depth);
          S.pop();
        }
        break;
      }
      case 'include': {
        const t = ctx.templates.get(n.name);
        if (t !== undefined && depth < INCLUDE_DEPTH) out += renderNodes(t, S, ctx, depth + 1);
        break;
      }
    }
  }
  return out;
}

/** `v`'s remaining path segments, each an own property, or undefined. */
function seg(v, rest) {
  for (let k = 0; k < rest.length; k++) {
    if (v === null || typeof v !== 'object' || !Object.hasOwn(v, rest[k])) return undefined;
    v = v[rest[k]];
  }
  return v;
}

// Root values a template render always carries (site, tags, recent plus the
// page's own values); a first name no `for` in the case binds reads straight
// from the root frame.
const ROOT_VARS = new Set(['site', 'tags', 'recent', 'page', 'posts', 'pager', 'tag']);

/** How a path resolves, decided once per case at parse time: a loop variable or
 * `loop` of an enclosing `for` (frame at a fixed depth from the top of the
 * scope chain), a root value, or the full scope-chain lookup. */
function resolveTemplatePath(path, forStack, forVars) {
  const first = path[0];
  const rest = path.slice(1);
  if (forStack.length > 0) {
    if (first === 'loop') return { mode: 'frame', d: 0, first, rest };
    for (let p = forStack.length - 1; p >= 0; p--) {
      if (forStack[p] === first) return { mode: 'frame', d: forStack.length - 1 - p, first, rest };
    }
  }
  if (ROOT_VARS.has(first) && !forVars.has(first)) return { mode: 'root', first, rest };
  return { mode: 'lookup', path };
}

/** A parsed node's path value in the scope chain, via its precomputed resolution. */
function resolveValue(S, res) {
  if (res.mode === 'lookup') return lookup(S, res.path);
  const base = res.mode === 'frame' ? S[S.length - 1 - res.d][res.first] : S[0][res.first];
  return seg(base, res.rest);
}

/** Annotate every path node of a parsed template with its resolution. */
function annotate(nodes, forVars, forStack) {
  for (const n of nodes) {
    if (n.kind === 'var' || n.kind === 'raw' || n.kind === 'if' || n.kind === 'for') {
      n.res = resolveTemplatePath(n.path, forStack, forVars);
    }
    if (n.kind === 'for') {
      forStack.push(n.name);
      annotate(n.body, forVars, forStack);
      forStack.pop();
    } else if (n.kind === 'if') {
      annotate(n.then, forVars, forStack);
      if (n.else !== null) annotate(n.else, forVars, forStack);
    }
  }
}

